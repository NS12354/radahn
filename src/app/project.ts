/**
 * Project file format (project.formframe.json). Plain JSON, stable key order,
 * code stored as separate string entries so it diffs cleanly in Git. When saved
 * to a folder (File System Access API) the firmware files and CAD model are
 * written next to the JSON instead of embedded.
 */
export const FORMAT_VERSION = 1;

export type PartKey = 'body' | 'dial' | 'face' | 'led' | 'mount';
export type BindRole = 'body' | 'dial' | 'screen' | 'press' | 'led' | 'ignore';

/** Primitive shapes for built models. Sizes are the part's bounding box in mm; the front of the product faces +Z. */
export type ShapeKind = 'box' | 'rbox' | 'cyl' | 'tube' | 'sphere' | 'torus' | 'cone' | 'disc' | 'rect' | 'mesh';

/**
 * Editable polygon mesh (shape 'mesh'). Vertices are normalised to the part's
 * bounding box (-0.5…0.5 on each axis) so `size` and `pos` keep meaning the
 * box and its centre, like every other shape. Faces are vertex-index loops
 * (counter-clockwise seen from outside); `e` holds loose edges not on a face.
 */
export interface MeshData { v: number[]; f: number[][]; e?: [number, number][] }

export interface BuiltPart {
  id: string;
  name: string;
  shape: ShapeKind;
  /** Bounding box in mm: [width X, height Y, depth Z]. */
  size: [number, number, number];
  /** Centre position in mm. */
  pos: [number, number, number];
  /** Rotation in degrees (XYZ order). */
  rot: [number, number, number];
  color: string;
  finish: string;
  role: BindRole;
  /** rbox: corner radius mm · tube: inner diameter mm · cone: top/bottom diameter ratio. */
  param?: number;
  /** LED parts: split into this many lit segments (one per pixel). */
  segments?: number;
  /** Repeat the part: `linear` steps by `step` mm; `radial` copies around the Z axis through `center`. */
  array?: { n: number; mode: 'linear' | 'radial'; step?: [number, number, number]; center?: [number, number] };
  /** 'shell' parts form the enclosure (X-ray fades them); 'internal' parts are components inside it. */
  kind?: 'shell' | 'internal';
  /** Exploded view moves the part this many steps along Z. */
  layer?: number;
  /** Generated by auto build (replaced on rebuild); user parts are kept. */
  auto?: boolean;
  /** Electronics component (uid) or 'board' this part belongs to. */
  comp?: string;
  /** Geometry for shape 'mesh'. */
  mesh?: MeshData;
  /** Smooth shading (otherwise flat, like Blender's default). */
  smooth?: boolean;
  /** Set once the part has been through Blender (live link): Blender's geometry hash and object matrix. */
  bl?: { hash: string; sig: string; matrix: number[]; pos: [number, number, number]; rot: [number, number, number] };
  /** Robots: the part this one is attached to. It moves with its parent (and its joint, if it has one). */
  parent?: string;
  /** Robots: how this part moves relative to its parent. Pivot and axis are in model space, at rest. */
  joint?: Joint;
  /** A detailed model of real hardware instead of the plain shape, e.g. "servo:mg996r", "pcb:picow" (see scene/detail.ts). */
  detail?: string;
  /** Robots: a foot (legged robots stand and walk on these). Its contact point is the bottom of the part. */
  foot?: boolean;
}

export type JointType = 'revolute' | 'prismatic' | 'wheel' | 'fixed';
export interface Joint {
  type: JointType;
  /** Pivot point (revolute/wheel) or start point (prismatic), mm, model space at rest. */
  pivot: [number, number, number];
  /** Rotation / slide axis, model space at rest (normalised when used). */
  axis: [number, number, number];
  /** Limits: degrees (revolute) or mm (prismatic). Wheels spin freely. */
  min?: number;
  max?: number;
  /**
   * What moves it: an electronics component (servo, PCA9685 channel, stepper, motor driver channel).
   * The joint angle = (actuator angle − 90°) × (invert ? −1 : 1) + offset, for servos.
   */
  drive?: { comp: string; channel?: number; invert?: boolean; offset?: number };
  /** Encoders that report this wheel's rotation (component uids). */
  sensors?: string[];
}

/** A robot's surroundings: a floor, things to bump into and a line to follow (mm, Y up). */
export interface World {
  size: number;
  /** pos: XZ centre (mm); size: [width, height, depth]; rot: yaw (degrees about Y); pick: a gripper can pick it up. */
  obstacles: { shape: 'box' | 'cyl'; pos: [number, number]; size: [number, number, number]; color?: string; rot?: number; pick?: boolean; name?: string }[];
  /** A dark line on the floor (closed loop through these XZ points). */
  track?: { points: [number, number][]; width: number };
}
export interface RobotSpec {
  kind: 'arm' | 'rover' | 'legs' | 'custom';
  /** How the body moves: bolted down, on wheels, or on legs. */
  mobile: 'fixed' | 'wheels' | 'legs';
  /** Total mass in grams (legs: load on the servos). */
  mass: number;
  world?: World;
  /** Rigid-body physics (gravity, torque limits, friction) instead of the simple motion model. */
  physics?: boolean;
  /** Poses recorded in teach mode: joint part id → value. */
  poses?: { name: string; joints: Record<string, number> }[];
}

export interface AutoBuildOpts {
  style: 'auto' | 'round' | 'rect';
  wall: number;
  clearance: number;
  battery: boolean;
  mount: 'wall' | 'desk' | 'none';
}

export interface BuiltModel {
  parts: BuiltPart[];
  xray: boolean;
  auto: AutoBuildOpts;
  /** Notes from the last auto build. */
  notes: string[];
  /** Bumped on every edit so the studio and modeler windows never adopt an older copy. */
  rev?: number;
  /** Set when the model is a robot: how it moves and its surroundings. */
  robot?: RobotSpec;
}

export const defaultAutoOpts = (): AutoBuildOpts => ({ style: 'auto', wall: 2, clearance: 1, battery: false, mount: 'none' });

/** A fresh built model: one rounded-box housing, like Blender's default cube. */
export function newBuiltModel(): BuiltModel {
  return { parts: [{ id: newUid(), name: 'Housing', shape: 'rbox', size: [80, 60, 30], pos: [0, 0, 0], rot: [0, 0, 0], param: 6, color: '#ece9e4', finish: 'matte', role: 'body', kind: 'shell', layer: 0 }], xray: false, auto: defaultAutoOpts(), notes: [] };
}

export interface Transition { from: string; trig: string; to: string; act: string; led: string; hap: boolean; snd: boolean }
export interface Comment { p: [number, number, number]; text: string; part: string; t: string }

export interface Project {
  format: 'formframe';
  version: number;
  name: string;
  product: {
    /** 'none' = blank project, no model yet. */
    source: 'parametric' | 'imported' | 'built' | 'none';
    parametric: { dia: number; depth: number; proc: 'im' | 'cnc' | 'sla'; parts: Record<PartKey, { name: string; color: string; finish: string }> };
    imported: null | {
      fileName: string; format: 'glb' | 'gltf' | 'stl' | 'step';
      /** base64 when embedded; omitted when saved as a sibling file in a project folder */
      data?: string;
      bindings: Record<string, BindRole>;
    };
    /** Model built in-app from primitives (by hand or by auto build). */
    built: BuiltModel | null;
    qty: number;
  };
  internals: Record<string, boolean>;
  interactions: Transition[];
  electronics: {
    board: string;
    comps: CompInstance[];
    files: Record<string, string>;
    activeFile: string;
    filesEdited: boolean;
    /** Which code "Reset code" and wiring changes regenerate: the The First Step or an empty skeleton. */
    starter: 'thermostat' | 'blank' | 'robot';
    /** Robot template this project came from (its code is regenerated while unedited). */
    robot?: string;
    /** Parts imported from a link or defined by hand, carried with the project. */
    custom?: Record<string, CustomPartSpec>;
  };
  env: { roomC: number; rh: number };
  comments: Comment[];
  /** Plan tab: tasks, activity log, milestones, AI summary */
  plan?: PlanData;
}

const COLORS = ['#ff7a2f', '#3aa0ff', '#33c27f', '#e5c07b', '#c678dd', '#56b6c2', '#ff5c8a', '#a0a0ff', '#ffd166', '#8ce99a', '#f78c6c', '#89ddff'];
export const nextColor = (i: number) => COLORS[i % COLORS.length];
let uidN = 0;
export const newUid = () => 'c' + Date.now().toString(36) + (uidN++).toString(36);

export function kitFor(boardId: string): CompInstance[] {
  const preset = KIT_PRESETS[boardId] ?? {};
  return KIT.map((type, i) => {
    const pins: Record<string, number | null> = {};
    COMPONENTS[type].roles.forEach((r, k) => (pins[r.id] = preset[type]?.[k] ?? null));
    return { uid: newUid(), type, pins, color: nextColor(i) };
  });
}

