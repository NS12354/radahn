/** Starter code for the project's board, following its starter kind. */
export function starterFiles(b: BoardDef, e: Project['electronics']): Record<string, string> {
  if (e.starter === 'robot' && e.robot) return robotFiles(b, e.robot, e.comps);
  return e.starter === 'blank' ? demoFiles(b, e.comps) ?? blankFiles(b) : { ...defaultFiles(b, e.comps), ...libsFor(b, e.comps) };
}

/** A truly empty project: no model, no parts, no interactions, a skeleton code file. */
export function blankProject(board = 'picow'): Project {
  const d = defaultProject();
  const files = blankFiles(BOARDS[board]);
  return {
    ...d,
    name: 'Untitled project',
    product: { ...d.product, source: 'none', imported: null },
    internals: Object.fromEntries(Object.keys(d.internals).map(k => [k, false])),
    interactions: [],
    electronics: { board, comps: [], files, activeFile: Object.keys(files)[0], filesEdited: false, starter: 'blank' },
    comments: [],
  };
}

/** Validate + migrate a loaded project. Throws with a readable message. */
export function parseProject(json: string): Project {
  let p: any;
  try { p = JSON.parse(json); } catch (e) { throw new Error('Not valid JSON: ' + (e as Error).message); }
  if (p?.format !== 'formframe') throw new Error('Not a Formframe project (missing "format": "formframe").');
  if (typeof p.version !== 'number' || p.version > FORMAT_VERSION) throw new Error(`Unsupported project version ${p.version}.`);
  const d = defaultProject();
  const merged: Project = { ...d, ...p, product: { ...d.product, ...p.product, parametric: { ...d.product.parametric, ...p.product?.parametric } }, electronics: { ...d.electronics, ...p.electronics }, env: { ...d.env, ...p.env } };
  merged.plan = { ...emptyPlan(), ...(p.plan ?? {}) };
  if (merged.product.built) merged.product.built = { ...merged.product.built, xray: !!merged.product.built.xray, notes: merged.product.built.notes ?? [], auto: { ...defaultAutoOpts(), ...merged.product.built.auto } };
  for (const s of Object.values(merged.electronics.custom ?? {})) if (s?.id && Array.isArray(s.roles)) registerCustom(s);
  if (!BOARDS[merged.electronics.board]) throw new Error(`Unknown board "${merged.electronics.board}".`);
  for (const c of merged.electronics.comps) if (!COMPONENTS[c.type]) throw new Error(`Unknown component type "${c.type}".`);
  return merged;
}

/** Stable, diff-friendly serialization. */
export function serializeProject(p: Project, opts: { embedModel?: boolean } = {}): string {
  const clone: Project = JSON.parse(JSON.stringify(p));
  if (opts.embedModel === false && clone.product.imported) delete clone.product.imported.data;
  return JSON.stringify(clone, null, 2) + '\n';
}

