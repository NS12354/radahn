import type { Transition } from '../app/project';

export const STATES: Record<string, string> = { home: 'Home', set: 'Set temp', eco: 'Eco', away: 'Away' };
export const TRIGGERS: Record<string, string> = { dial_cw: 'Dial ↻', dial_ccw: 'Dial ↺', press: 'Press', long: 'Long press', idle: 'Idle 3 s' };
export const ACTIONS: Record<string, string> = { none: '—', up: 'Target +0.5°', down: 'Target −0.5°', save: 'Save target' };
export const LEDS: Record<string, string> = { none: 'No LED', heat: 'LED orange', cool: 'LED blue', ok: 'LED green', white: 'LED white' };
export const LEDCOL: Record<string, number> = { heat: 0xff7a2f, cool: 0x3aa0ff, ok: 0x33c27f, white: 0xffffff };

export interface SMState { state: string; target: number; room: number }

/** Pure transition function: unit-testable, also used by the firmware exporter. */
export function step(trs: Transition[], s: SMState, trig: string): { next: SMState; t: Transition | null; index: number } {
  const index = trs.findIndex(t => t.from === s.state && t.trig === trig);
  if (index < 0) return { next: s, t: null, index };
  const t = trs[index];
  let target = s.target;
  if (t.act === 'up') target = Math.min(32, target + 0.5);
  if (t.act === 'down') target = Math.max(10, target - 0.5);
  return { next: { ...s, state: t.to, target }, t, index };
}

export function hvac(s: SMState) { return s.target > s.room + 0.3 ? 'heat' : s.target < s.room - 0.3 ? 'cool' : 'hold'; }

function ticks(c: CanvasRenderingContext2D, lo: number, hi: number, on: string) {
  for (let i = 0; i <= 80; i++) {
    const tv = 10 + i * (22 / 80), a = ((-225 + (i * 270) / 80) * Math.PI) / 180;
    const lit = tv >= Math.min(lo, hi) - 0.01 && tv <= Math.max(lo, hi) + 0.01;
    c.strokeStyle = lit ? on : '#2b3038'; c.lineWidth = lit ? 5 : 3;
    const r2 = lit ? 198 : 206;
    c.beginPath(); c.moveTo(256 + Math.cos(a) * 226, 256 + Math.sin(a) * 226); c.lineTo(256 + Math.cos(a) * r2, 256 + Math.sin(a) * r2); c.stroke();
  }
}

/** Screen designs for the interaction prototype (512×512, circular display). */
export function drawScreen(cv: HTMLCanvasElement, s: SMState) {
  const c = cv.getContext('2d')!;
  const g = c.createRadialGradient(256, 200, 20, 256, 256, 300); g.addColorStop(0, '#141a22'); g.addColorStop(1, '#06080b');
  c.fillStyle = g; c.fillRect(0, 0, 512, 512);
  c.textAlign = 'center'; c.textBaseline = 'middle';
  const h = hvac(s), ac = h === 'heat' ? '#ff7a2f' : h === 'cool' ? '#3aa0ff' : '#8b95a3';
  if (s.state === 'home' || s.state === 'set') {
    ticks(c, s.room, s.target, ac);
    if (s.state === 'home') {
      c.fillStyle = '#8b95a3'; c.font = '500 22px Inter'; c.fillText('INDOOR', 256, 150);
      c.fillStyle = '#fff'; c.font = '200 150px Inter'; c.fillText(s.room.toFixed(0) + '°', 268, 262);
      c.fillStyle = ac; c.font = '600 24px Inter';
      c.fillText(h === 'heat' ? `HEATING TO ${s.target.toFixed(1)}°` : h === 'cool' ? `COOLING TO ${s.target.toFixed(1)}°` : 'HOLDING', 256, 362);
      c.fillStyle = '#5d6672'; c.font = '400 20px Inter'; c.fillText('42% RH', 256, 400);
    } else {
      c.fillStyle = ac; c.font = '600 22px Inter'; c.fillText(h === 'heat' ? 'SET HEAT' : h === 'cool' ? 'SET COOL' : 'SET TEMP', 256, 150);
      c.fillStyle = '#fff'; c.font = '200 150px Inter'; c.fillText(s.target.toFixed(1), 256, 262);
      c.fillStyle = '#8b95a3'; c.font = '400 22px Inter'; c.fillText(`Now ${s.room.toFixed(1)}°  ·  press to save`, 256, 362);
    }
  } else if (s.state === 'eco') {
    c.save(); c.translate(256, 200); c.rotate(-0.6); c.fillStyle = '#33c27f';
    c.beginPath(); c.ellipse(0, 0, 34, 62, 0, 0, Math.PI * 2); c.fill();
    c.strokeStyle = '#06080b'; c.lineWidth = 4; c.beginPath(); c.moveTo(0, -50); c.lineTo(0, 58); c.stroke(); c.restore();
    c.fillStyle = '#fff'; c.font = '300 64px Inter'; c.fillText('ECO', 256, 310);
    c.fillStyle = '#8b95a3'; c.font = '400 22px Inter'; c.fillText('Holding 17° – 26°', 256, 360);
  } else {
    c.fillStyle = '#cfd6e0'; c.beginPath(); c.arc(256, 200, 52, 0, Math.PI * 2); c.fill();
    c.fillStyle = '#0c1016'; c.beginPath(); c.arc(280, 184, 48, 0, Math.PI * 2); c.fill();
    c.fillStyle = '#fff'; c.font = '300 64px Inter'; c.fillText(STATES[s.state]?.toUpperCase() ?? s.state, 256, 310);
    c.fillStyle = '#8b95a3'; c.font = '400 22px Inter'; c.fillText('Safety range 10° – 30°', 256, 360);
  }
}

/** Generate an Arduino C++ state-machine skeleton from the interaction table. */
export function exportFirmware(trs: Transition[], projectName: string, target = 22) {
  const E: Record<string, string> = { dial_cw: 'DIAL_CW', dial_ccw: 'DIAL_CCW', press: 'PRESS', long: 'LONG_PRESS', idle: 'IDLE' };
  const ST: Record<string, string> = { home: 'HOME', set: 'SET_TEMP', eco: 'ECO', away: 'AWAY' };
  const hex = (k: string) => '0x' + LEDCOL[k].toString(16).toUpperCase().padStart(6, '0');
  let s = `// Generated by Formframe from "${projectName}"\n// ${trs.length} interactions, ${Object.keys(STATES).length} states\n\n#include <Arduino.h>\n#include "ui.h"   // drawScreen(State)\n#include "hw.h"   // ledPulse(rgb), haptic(), click(), readEncoderDetents(), readButton()\n\nenum State { HOME, SET_TEMP, ECO, AWAY };\nenum Event { DIAL_CW, DIAL_CCW, PRESS, LONG_PRESS, IDLE };\n\nState state = HOME;\nfloat target = ${target.toFixed(1)}f;\nunsigned long lastInput = 0;\n\nvoid go(State s) { state = s; drawScreen(s); }\n\nvoid handle(Event e) {\n  lastInput = millis();\n  switch (state) {\n`;
  for (const st of Object.keys(STATES)) {
    const ts = trs.filter(t => t.from === st);
    s += `    case ${ST[st]}:\n`;
    for (const t of ts) {
      const body: string[] = [];
      if (t.act === 'up') body.push('target = min(target + 0.5f, 32.0f);');
      if (t.act === 'down') body.push('target = max(target - 0.5f, 10.0f);');
      if (t.act === 'save') body.push('saveTarget(target);');
      if (t.led !== 'none') body.push(`ledPulse(${hex(t.led)});`);
      if (t.hap) body.push('haptic();');
      if (t.snd) body.push('click();');
      body.push(`go(${ST[t.to]});`);
      s += `      if (e == ${E[t.trig]}) { ${body.join(' ')} return; }\n`;
    }
    if (!ts.length) s += '      // no interactions defined\n';
    s += '      break;\n';
  }
  s += `  }\n}\n\nvoid setup() { hwInit(); go(HOME); }\n\nvoid loop() {\n  int d = readEncoderDetents();\n  while (d > 0) { handle(DIAL_CW); d--; }\n  while (d < 0) { handle(DIAL_CCW); d++; }\n  ButtonEvt b = readButton(600);\n  if (b == SHORT) handle(PRESS);\n  if (b == LONG) handle(LONG_PRESS);\n  if (lastInput && millis() - lastInput > 3000) { lastInput = 0; handle(IDLE); }\n}\n`;
  return s;
}
